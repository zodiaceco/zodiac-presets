// Regenerates `src/pendle/chains.ts`, Pendle's router and the wrapped native
// token on every chain both Pendle and Zodiac are deployed on:
//
// - The chains, the router and the wrapped native token come from Pendle's
//   deployments in github.com/pendle-finance/pendle-core-v2-public
//   (`deployments/<chainId>-core.json`). Chains without a router are left out.
// - The router forwards each function to a facet, and the facets can differ by
//   chain. So every router is asked on chain (`selectorToFacet`) whether it
//   serves each function the presets use; a chain where one is missing fails
//   the sync.
//
//   bun sync:pendle           rewrite the file
//   bun sync:pendle --check   exit 1 if the file is out of date
//
// Public RPCs are used by default; set `RPC_<chainId>` to use another.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { CHAIN_IDS } from '@zodiaceco/sdk/allow'
import {
  Contract,
  getAddress,
  Interface,
  JsonRpcProvider,
  ZeroAddress,
} from 'ethers'
import { format, resolveConfig } from 'prettier'
import routerAbi from '../abis/any/pendle_router.json'

const OUT = fileURLToPath(new URL('../src/pendle/chains.ts', import.meta.url))
const REPO = 'pendle-finance/pendle-core-v2-public'

const RPCS: Record<number, string> = {
  1: 'https://ethereum-rpc.publicnode.com',
  10: 'https://optimism-rpc.publicnode.com',
  56: 'https://bsc-rpc.publicnode.com',
  130: 'https://unichain-rpc.publicnode.com',
  146: 'https://sonic-rpc.publicnode.com',
  999: 'https://rpc.hyperliquid.xyz/evm',
  5000: 'https://mantle-rpc.publicnode.com',
  8453: 'https://base-rpc.publicnode.com',
  9745: 'https://rpc.plasma.to',
  42161: 'https://arbitrum-one-rpc.publicnode.com',
  80094: 'https://berachain-rpc.publicnode.com',
}

// The router functions the presets in src/pendle/index.ts permit.
const FUNCTIONS = [
  'swapExactTokenForPt',
  'swapExactPtForToken',
  'redeemPyToToken',
  'exitPostExpToToken',
  'addLiquiditySingleToken',
  'removeLiquiditySingleToken',
  'swapExactTokenForYt',
  'swapExactYtForToken',
  'redeemDueInterestAndRewards',
]

const github = async (path: string, raw = false) => {
  const url = raw
    ? `https://raw.githubusercontent.com/${REPO}/main/${path}`
    : `https://api.github.com/repos/${REPO}/contents/${path}`
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  return raw ? response.text() : response.json()
}

type Chain = {
  name: string
  chain: number
  router: string
  wrappedNative: string
}

/** Pendle's chains that Zodiac supports and that have a router. */
const pendleChains = async (): Promise<Chain[]> => {
  const names = new Map(
    Object.entries(CHAIN_IDS).map(([prefix, id]) => [id as number, prefix])
  )
  const files = (
    (await github('deployments')) as { name: string; type: string }[]
  ).filter((entry) => /^\d+-core\.json$/.test(entry.name))

  const chains = await Promise.all(
    files.map(async ({ name: file }): Promise<Chain | undefined> => {
      const chain = Number(file.split('-')[0])
      const name = names.get(chain)
      if (name == null) return // not a Zodiac chain
      const deployment = JSON.parse(
        await github(`deployments/${file}`, true)
      ) as { router?: string; network: { wrappedNative: string } }
      if (deployment.router == null) return // no router there
      return {
        name,
        chain,
        router: getAddress(deployment.router),
        wrappedNative: getAddress(deployment.network.wrappedNative),
      }
    })
  )

  return chains
    .filter((c): c is Chain => c != null)
    .sort((a, b) => a.chain - b.chain)
}

/** Throws unless the router on `chain` serves every function in FUNCTIONS. */
const checkRouter = async ({ chain, router }: Chain) => {
  const rpc = process.env[`RPC_${chain}`] ?? RPCS[chain]
  if (rpc == null)
    throw new Error(`No RPC for chain ${chain}: set RPC_${chain}.`)
  const provider = new JsonRpcProvider(rpc, chain, { staticNetwork: true })
  const storage = new Contract(
    router,
    ['function selectorToFacet(bytes4) view returns (address)'],
    provider
  )
  const iface = new Interface(routerAbi)

  for (const name of FUNCTIONS) {
    const selector = iface.getFunction(name)!.selector
    const facet = (await storage.selectorToFacet(selector)) as string
    if (facet === ZeroAddress) {
      throw new Error(
        `The Pendle router on chain ${chain} does not serve ${name} (${selector}).`
      )
    }
  }
}

const render = async (chains: Chain[]) => {
  const body = chains
    .map(
      ({ name, chain, router, wrappedNative }) =>
        `${chain}: { // ${name}\n router: '${router}',\n wrappedNative: '${wrappedNative}',\n },`
    )
    .join('\n')

  const source = `// Generated by \`bun sync:pendle\` (scripts/sync-pendle.ts) from Pendle's
// deployments, with every router checked on chain. Do not edit.

import type { Address } from '../kit'

/**
 * Pendle on every chain both Pendle and Zodiac are deployed on, by chain id:
 * the router (PendleRouterV4) and the chain's wrapped native token, which the
 * router can unwrap before a deposit.
 */
export const PENDLE = {
${body}
} as const satisfies Record<number, { router: Address; wrappedNative: Address }>
`
  return format(source, { ...(await resolveConfig(OUT)), filepath: OUT })
}

const chains = await pendleChains()
await Promise.all(chains.map(checkRouter))
const generated = await render(chains)

if (process.argv.includes('--check')) {
  const current = await readFile(OUT, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error(`${OUT} is out of date: run \`bun sync:pendle\`.`)
    process.exit(1)
  }
  console.log(`${OUT} is up to date.`)
} else {
  await writeFile(OUT, generated)
  console.log(`Wrote ${OUT} (${chains.map((c) => c.name).join(', ')}).`)
}
