#!/usr/bin/env bun
// Types the contracts in `zodiac.config.ts` as `Kit` in `src/kit.generated.d.ts`.
//
// `zodiac pull-contracts` fetches any missing ABIs and writes typings for a
// constellation repo, where they augment the global `AllowKit`. A package must
// not touch its users' globals, so this turns that file into a module
// exporting the same tree as `Kit`.
//
// pull-contracts never calls the Zodiac API, but loading the config asks for a
// key, so a placeholder stands in.

import { spawnSync } from 'bun'

const GENERATED = '.zodiac/allow.d.ts'
const OUT = 'src/kit.generated.d.ts'

const { exitCode } = spawnSync(['bunx', 'zodiac', 'pull-contracts'], {
  env: { ...process.env, ZODIAC_API_KEY: 'zodiac_codegen' },
  stdio: ['inherit', 'inherit', 'inherit'],
})

if (exitCode !== 0) process.exit(exitCode ?? 1)

const source = await Bun.file(GENERATED).text()

const start = source.indexOf('declare global {\n  interface AllowKit ')
// The `}` closing `declare global`, the first one in the first column.
const end = source.indexOf('\n}\n', start)

if (start === -1 || end === -1) {
  throw new Error(`${GENERATED} no longer declares a global AllowKit`)
}

const header = source
  .slice(0, start)
  .replace(
    '// AUTO-GENERATED by `zodiac pull-contracts`. Do not edit.',
    '// AUTO-GENERATED by `bun codegen`. Do not edit.'
  )
const tree = source
  .slice(start, end)
  .replace('declare global {\n  interface AllowKit ', 'export interface Kit ')
  .replace(/^  /gm, '')

await Bun.write(OUT, `${header}${tree.trimEnd()}\n`)
console.log(`Wrote ${OUT}`)
